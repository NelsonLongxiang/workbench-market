import {readFileSync,writeFileSync} from 'node:fs';
import {join,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {spawn} from 'node:child_process';
import {once} from 'node:events';
import assert from 'node:assert/strict';
const root=dirname(fileURLToPath(import.meta.url));
const names=['execution.mjs','fixtures.mjs','more-handlers.mjs','final-handlers.mjs','run-unit.mjs','completion-policy.json','coverage.json','candidates.json','material.md'];
const hash=name=>createHash('sha256').update(readFileSync(join(root,name))).digest('hex');
const files=names.map(path=>({path,sha256:hash(path)}));
const targetFiles=['server/src/index.ts','server/src/a2a.ts','server/src/db.ts','server/src/portal.ts'].map(path=>({path,sha256:createHash('sha256').update(readFileSync(join(root,'target',path))).digest('hex')}));
const before={started_at:new Date().toISOString(),target_sha:'d90f81abca809a48a893544d0bdd4c409be78526',archive_sha256:hash('target.tar.gz'),cwd:root,cmd:[process.execPath,'--disable-warning=ExperimentalWarning',join(root,'execution.mjs')],files,targetFiles};
writeFileSync(join(root,'execution-launch.json'),JSON.stringify(before,null,2));
const child=spawn(before.cmd[0],before.cmd.slice(1),{cwd:root,stdio:'inherit'});
const [code,signal]=await once(child,'close');
for(const f of files)assert.equal(hash(f.path),f.sha256,'test source changed during run');
const report=JSON.parse(readFileSync(join(root,'execution-report.json'),'utf8'));
assert.equal(code,0,'execution runner error, not product FAIL');
writeFileSync(join(root,'execution-provenance.json'),JSON.stringify({...before,finished_at:new Date().toISOString(),runner_pid:child.pid,runner_exit:{code,signal},report_run_id:report.run_id,report_sha256:hash('execution-report.json'),source_unchanged:true},null,2));
console.log('Versioned source identities verified; product predicates remain as actual FAIL/NEEDS, not runner exit status');
