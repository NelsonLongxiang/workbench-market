/** Native registry persistence only: not mounted or selected at runtime.
 * Caller owns URL admission, authentication, credential governance, cookie/type references and deletion cascade.
 * Full rows include auth_config: internal trusted callers only; never return directly to public API.
 */
import {withPgTransaction,type PgTransactionPool} from './pg-transaction.ts';
const editable=['name','url','type','icon','description','category','tags','enabled','health_path','sort','auth_config','cookie_set_id'] as const;
type Edit={name:string;url:string;type:string;icon:string;description:string;category:string;tags:string;enabled:number;health_path:string;sort:number;auth_config:string;cookie_set_id:number};
export class PgWorkbenchError extends Error {code:string;constructor(code:string){super(code);this.code=code;}}
const refuse=(code:string):never=>{throw new PgWorkbenchError(code);};
function safeInteger(n:unknown,min:number,max=Number.MAX_SAFE_INTEGER):number{if(typeof n!=='number'||!Number.isSafeInteger(n)||n<min||n>max)refuse('workbench_integer_invalid');return n as number;}
function text(s:unknown):string{if(typeof s!=='string'||s.includes(String.fromCharCode(0)))refuse('workbench_text_invalid');return s as string;}
function snapshot(input:Edit):unknown[]{
 const copied=editable.map(k=>input[k]);
 for(let i=0;i<editable.length;i++){
  const k=editable[i],v=copied[i];
  if(k==='enabled'){if(v!==0&&v!==1)refuse('workbench_enabled_invalid');}
  else if(k==='sort')safeInteger(v,-2147483648,2147483647);
  else if(k==='cookie_set_id')safeInteger(v,0);
  else text(v);
 }
 return copied;
}
function row(r:Record<string,unknown>){const id=Number(r.id),cookie=Number(r.cookie_set_id);safeInteger(id,1);safeInteger(cookie,0);return {...r,id,cookie_set_id:cookie};}
const now="to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS')";
/** Explicit new-table bootstrap, no defaults seeded and no IF NOT EXISTS acceptance. */
export async function createNewPgWorkbenchesSchema(pool:PgTransactionPool){
 await withPgTransaction(pool,async tx=>{await tx.query(`CREATE TABLE public.workbenches(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 1 AND 9007199254740991),
  name text NOT NULL,url text NOT NULL,type text NOT NULL DEFAULT 'web',icon text DEFAULT '',
  description text DEFAULT '',category text DEFAULT '',tags text DEFAULT '[]',enabled integer NOT NULL DEFAULT 1 CHECK(enabled IN (0,1)),
  health_path text DEFAULT '',last_status text DEFAULT 'unknown',last_checked_at text DEFAULT '',
  last_latency_ms integer,last_http_code integer,last_error text DEFAULT '',sort integer NOT NULL DEFAULT 0,
  auth_config text NOT NULL DEFAULT '',created_at text NOT NULL DEFAULT (`+now+`),updated_at text NOT NULL DEFAULT (`+now+`),
  cookie_set_id bigint NOT NULL DEFAULT 0 CHECK(cookie_set_id BETWEEN 0 AND 9007199254740991)
 )`);});
}
export function createPgWorkbenches(pool:PgTransactionPool){
 return Object.freeze({
  async create(input:Edit){const values=snapshot(input);return withPgTransaction(pool,async tx=>{
   const r=await tx.query('INSERT INTO public.workbenches('+editable.join(',')+') VALUES('+editable.map((_,i)=>'$'+(i+1)).join(',')+') RETURNING *',values);return row(r.rows[0]);
  });},
  async byId(rawId:number){const id=safeInteger(rawId,1);return withPgTransaction(pool,async tx=>{const r=await tx.query('SELECT * FROM public.workbenches WHERE id=$1',[id]);return r.rows.length?row(r.rows[0]):null;});},
  async list(){return withPgTransaction(pool,async tx=>(await tx.query('SELECT * FROM public.workbenches ORDER BY sort,id')).rows.map(row));},
  async update(rawId:number,input:Edit){const id=safeInteger(rawId,1),values=snapshot(input);return withPgTransaction(pool,async tx=>{
   const r=await tx.query('UPDATE public.workbenches SET '+editable.map((k,i)=>k+'=$'+(i+1)).join(',')+',updated_at='+now+' WHERE id=$13 RETURNING *',[...values,id]);return r.rows.length?row(r.rows[0]):null;
  });},
  async applyProbe(rawId:number,input:{status:string;latency:number|null;code:number|null;error:string}){
   const id=safeInteger(rawId,1),{status,latency,code,error}=input;
   if(!['up','down','unknown'].includes(status))refuse('workbench_probe_status_invalid');text(error);
   if(latency!==null)safeInteger(latency,0,2147483647);if(code!==null)safeInteger(code,100,599);
   return withPgTransaction(pool,async tx=>{
    const r=await tx.query('UPDATE public.workbenches SET last_status=$1,last_latency_ms=$2,last_http_code=$3,last_error=$4,last_checked_at='+now+' WHERE id=$5 RETURNING *',[status,latency,code,error,id]);return r.rows.length?row(r.rows[0]):null;
   });
  },
 });
}
