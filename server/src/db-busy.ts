/**
 * 库被别的连接锁着写的时候，这个连接最多等多久（毫秒）：SQLite 的 busy_timeout。
 *
 * 缺省是 0：一碰到写锁当场报 database is locked。部署切换时新旧两个进程短暂重叠、
 * 或者运维工具开了一个连接写一下，市场的写就会直接失败。等一个有上限的时间，短暂重叠不至于失败；超过上限照样报错，不无限等。
 * 这不改变「多个进程同时写同一个库还不支持」的口径：只是让短暂的重叠不直接失败。
 *
 * 市场主库、判定比对库用它；台库（worker 里）每次读写的等待取它和那一次读写时限中较小的一个，免得等锁等过了时限被看门狗强行中止。
 * 不依赖任何模块：worker 也要引它，不能把主库带进来。
 */
export const DB_BUSY_TIMEOUT_MS = 5000;
