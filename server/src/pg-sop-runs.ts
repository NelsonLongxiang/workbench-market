/** Native PG SOP persistence slice; intentionally not wired to the market entrypoint.
 * Inject a pool whose target/role has already been validated. No Redis, SQLite or implicit schema creation.
 * Callers still own authentication, run capabilities, manifest/field validation and callback delivery.
 */
import { withPgTransaction, type PgTransactionPool, type PgTransaction } from './pg-transaction.ts';

export type PgSopRun = {
  id: number; sop_slug: string; sop_version: number; status: string; started_by: string;
  data: string; cache_revision: number; started_at: string; updated_at: string; finished_at: string; upload_token: string;
};
export class PgSopRunError extends Error {
  code: string;
  constructor(code: string) { super(code); this.code = code; }
}
const refuse = (code: string): never => { throw new PgSopRunError(code); };
function integer(value: unknown, minimum: number, code: string): number {
  if (typeof value !== 'number' || !Number.isSafeInteger(value) || value < minimum) refuse(code);
  return value as number;
}
function objectData(text: string): Record<string, unknown> {
  if (typeof text !== 'string') refuse('sop_run_data_invalid');
  let value: unknown;
  try { value = JSON.parse(text); } catch { return refuse('sop_run_data_invalid'); }
  if (!value || typeof value !== 'object' || Array.isArray(value)) refuse('sop_run_data_invalid');
  return value as Record<string, unknown>;
}
function row(raw: Record<string, unknown>): PgSopRun {
  for (const field of ['id', 'cache_revision']) {
    const value = raw[field];
    if (!/^[0-9]+$/.test(String(value))) refuse('sop_run_integer_invalid');
    integer(Number(value), field === 'id' ? 1 : 0, 'sop_run_integer_invalid');
  }
  return { ...raw, id: Number(raw.id), cache_revision: Number(raw.cache_revision) } as PgSopRun;
}
const utcNow = "to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')";

/** Explicit NEW table bootstrap only, never startup migration or overwrite.
 * No IF NOT EXISTS: any preexisting object collision aborts the whole schema transaction.
 * TEXT preserves legacy JSON bytes/timestamps; a future importer must validate all historical rows.
 * cache_revision trigger advances even same-value/legacy direct data/status writes (ABA protection).
 */
export async function createNewPgSopRunsSchema(pool: PgTransactionPool): Promise<void> {
  await withPgTransaction(pool, async tx => {
    await tx.query(`CREATE TABLE public.sop_runs (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 1 AND 9007199254740991),
      sop_slug text NOT NULL, sop_version integer NOT NULL CHECK(sop_version > 0),
      status text NOT NULL DEFAULT 'running' CHECK(status IN ('running','finished')),
      started_by text NOT NULL DEFAULT '', data text NOT NULL DEFAULT '{}',
      cache_revision bigint NOT NULL DEFAULT 0 CHECK(cache_revision BETWEEN 0 AND 9007199254740991),
      started_at text NOT NULL DEFAULT (` + utcNow + `), updated_at text NOT NULL DEFAULT (` + utcNow + `),
      finished_at text NOT NULL DEFAULT '', upload_token text NOT NULL DEFAULT ''
    )`);
    await tx.query('CREATE INDEX idx_sop_runs_slug ON public.sop_runs(sop_slug,status)');
    await tx.query(`CREATE FUNCTION public.wm_sop_runs_revision() RETURNS trigger LANGUAGE plpgsql AS $fn$
      BEGIN NEW.cache_revision := OLD.cache_revision + 1; RETURN NEW; END;
    $fn$`);
    await tx.query(`CREATE TRIGGER sop_runs_cache_revision BEFORE UPDATE OF data,status ON public.sop_runs
      FOR EACH ROW EXECUTE FUNCTION public.wm_sop_runs_revision()`);
  });
}

export function createPgSopRuns(pool: PgTransactionPool) {
  async function locked(tx: PgTransaction, id: number, expected: number): Promise<PgSopRun> {
    integer(id, 1, 'sop_run_id_invalid'); integer(expected, 0, 'sop_run_revision_invalid');
    const found = await tx.query('SELECT * FROM public.sop_runs WHERE id=$1 FOR UPDATE', [id]);
    if (!found.rows.length) refuse('sop_run_not_found');
    const current = row(found.rows[0]);
    if (current.status !== 'running') refuse('sop_run_not_running');
    if (current.cache_revision !== expected) refuse('sop_run_revision_conflict');
    return current;
  }
  async function persist(tx: PgTransaction, id: number, expected: number, data: string, finish: boolean): Promise<PgSopRun> {
    const saved = await tx.query(`UPDATE public.sop_runs SET data=$1, updated_at=` + utcNow +
      (finish ? `, status='finished', finished_at=` + utcNow : '') +
      " WHERE id=$2 AND cache_revision=$3 AND status='running' RETURNING *", [data, id, expected]);
    if (saved.rows.length !== 1) refuse('sop_run_revision_conflict');
    const updated = row(saved.rows[0]);
    if (updated.cache_revision !== expected + 1) refuse('sop_run_generation_not_advanced');
    return updated;
  }
  return Object.freeze({
    async create(input: { slug: string; version: number; startedBy: string; uploadToken: string }): Promise<PgSopRun> {
      // Snapshot once before validation and before checkout/BEGIN can yield to caller mutations.
      const { slug, version, startedBy, uploadToken } = input;
      if (typeof slug !== 'string' || !/^[a-z0-9][a-z0-9-]{0,63}$/.test(slug)) refuse('sop_run_slug_invalid');
      integer(version, 1, 'sop_run_version_invalid');
      if (version > 2147483647) refuse('sop_run_version_invalid');
      if (typeof startedBy !== 'string' || typeof uploadToken !== 'string') refuse('sop_run_create_invalid');
      return withPgTransaction(pool, async tx => {
        const created = await tx.query('INSERT INTO public.sop_runs(sop_slug,sop_version,started_by,upload_token) VALUES($1,$2,$3,$4) RETURNING *', [slug,version,startedBy,uploadToken]);
        return row(created.rows[0]);
      });
    },
    async byId(id: number): Promise<PgSopRun | null> {
      integer(id, 1, 'sop_run_id_invalid');
      return withPgTransaction(pool, async tx => {
        const found = await tx.query('SELECT * FROM public.sop_runs WHERE id=$1', [id]);
        return found.rows.length ? row(found.rows[0]) : null;
      });
    },
    async checkpoint(id: number, expected: number, data: string): Promise<PgSopRun> {
      objectData(data);
      return withPgTransaction(pool, async tx => { await locked(tx,id,expected); return persist(tx,id,expected,data,false); });
    },
    async saveStep(id: number, expected: number, key: string, value: unknown): Promise<PgSopRun> {
      if (typeof key !== 'string' || !/^[A-Za-z0-9_-]+$/.test(key)) refuse('sop_run_step_invalid');
      // Serialize before the transaction: never retain caller-owned mutable values across await.
      let serialized: string;
      try { serialized = JSON.stringify({ [key]: value ?? null }); } catch { return refuse('sop_run_data_invalid'); }
      const patch = objectData(serialized);
      if (!Object.hasOwn(patch, key)) refuse('sop_run_data_invalid');
      return withPgTransaction(pool, async tx => {
        const current = await locked(tx,id,expected), data = objectData(current.data);
        // Object spread treats __proto__ as data, not prototype mutation.
        return persist(tx,id,expected,JSON.stringify({ ...data, ...patch }),false);
      });
    },
    async finish(id: number, expected: number, data: string): Promise<PgSopRun> {
      objectData(data);
      return withPgTransaction(pool, async tx => { await locked(tx,id,expected); return persist(tx,id,expected,data,true); });
    },
  });
}
