/** Native submission storage only; not mounted. Caller owns app existence/auth/contract and event delivery.
 * Idempotency compares exact serialized JSON bytes, including soft-deleted rows; never resurrect on retry.
 */
import {withPgTransaction,type PgTransactionPool} from './pg-transaction.ts';
export class PgAppDataError extends Error{code:string;constructor(code:string){super(code);this.code=code;}}
const refuse=(code:string):never=>{throw new PgAppDataError(code);};
function text(v:unknown){if(typeof v!=='string'||v.includes(String.fromCharCode(0)))refuse('app_data_text_invalid');return v as string;}
function slugOf(v:string){if(!/^[a-z0-9][a-z0-9-]{0,63}$/.test(text(v)))refuse('app_data_slug_invalid');return v;}
function integer(v:unknown,min:number){if(typeof v!=='number'||!Number.isSafeInteger(v)||v<min)refuse('app_data_integer_invalid');return v as number;}
function row(r:Record<string,unknown>){return {...r,id:integer(Number(r.id),1)};}
const now="to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS')";
export async function createNewPgAppDataSchema(pool:PgTransactionPool){await withPgTransaction(pool,async tx=>{
 await tx.query(`CREATE TABLE public.app_data(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 1 AND 9007199254740991),
 app_slug text NOT NULL,data text NOT NULL DEFAULT '{}',created_by text NOT NULL DEFAULT '',created_at text NOT NULL DEFAULT (`+now+`),
 deleted_at text NOT NULL DEFAULT '',idempotency_key text NOT NULL DEFAULT '')`);
 await tx.query('CREATE INDEX idx_app_data_slug ON public.app_data(app_slug,created_at)');
 await tx.query("CREATE UNIQUE INDEX idx_app_data_idem ON public.app_data(app_slug,idempotency_key) WHERE idempotency_key<>''");
});}
export function createPgAppData(pool:PgTransactionPool){return Object.freeze({
 async submit(rawSlug:string,input:{data:unknown;createdBy?:string;idempotencyKey?:string}){
  const slug=slugOf(rawSlug),{data,createdBy='',idempotencyKey=''}=input;
  const key=text(idempotencyKey),actor=text(createdBy).trim().slice(0,128);
  if(key&&!/^[A-Za-z0-9_.:-]{1,128}$/.test(key))refuse('app_data_key_invalid');
  let serialized:string|undefined;try{serialized=JSON.stringify(data);}catch{return refuse('app_data_json_invalid');}
  if(serialized===undefined||Buffer.byteLength(serialized)>1048576)refuse('app_data_json_invalid');const json=serialized as string;
  return withPgTransaction(pool,async tx=>{
   const inserted=await tx.query("INSERT INTO public.app_data(app_slug,data,created_by,idempotency_key) VALUES($1,$2,$3,$4) ON CONFLICT(app_slug,idempotency_key) WHERE idempotency_key<>'' DO NOTHING RETURNING *",[slug,json,actor,key]);
   if(inserted.rows.length)return {duplicate:false,record:row(inserted.rows[0])};
   // Separate READ COMMITTED statement sees a concurrent winner after ON CONFLICT waits.
   const existing=(await tx.query('SELECT * FROM public.app_data WHERE app_slug=$1 AND idempotency_key=$2 FOR SHARE',[slug,key])).rows[0];
   if(!existing)refuse('app_data_retry_state_missing');
   if(existing.data!==json)refuse('app_data_idempotency_conflict');
   return {duplicate:true,record:row(existing)};
  });
 },
 async page(rawSlug:string,rawBefore=0,rawLimit=50){const slug=slugOf(rawSlug),before=integer(rawBefore,0),limit=integer(rawLimit,1);if(limit>200)refuse('app_data_limit_invalid');return withPgTransaction(pool,async tx=>(await tx.query("SELECT id,data,created_by,created_at FROM public.app_data WHERE app_slug=$1 AND deleted_at='' AND ($2::bigint=0 OR id<$2) ORDER BY id DESC LIMIT $3",[slug,before,limit])).rows.map(row));},
 async softDelete(rawSlug:string,rawId:number){const slug=slugOf(rawSlug),id=integer(rawId,1);return withPgTransaction(pool,async tx=>(await tx.query("UPDATE public.app_data SET deleted_at="+now+" WHERE app_slug=$1 AND id=$2 AND deleted_at='' RETURNING id",[slug,id])).rows.length===1);},
});}
